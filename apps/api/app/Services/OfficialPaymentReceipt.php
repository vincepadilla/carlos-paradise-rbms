<?php

namespace App\Services;

use Carbon\CarbonImmutable;
use Illuminate\Support\Facades\DB;

class OfficialPaymentReceipt
{
    public function download(object $payment)
    {
        abort_unless($payment->status === 'approved', 422, 'The official receipt is available after payment approval.');

        $details = DB::table('payments as p')
            ->join('reservations as r', 'r.id', '=', 'p.reservation_id')
            ->join('villas as v', 'v.id', '=', 'r.villa_id')
            ->join('payment_methods as m', 'm.id', '=', 'p.payment_method_id')
            ->where('p.id', $payment->id)
            ->first([
                'p.id', 'p.amount', 'p.currency', 'p.reference_number', 'p.payment_date',
                'r.booking_reference', 'r.contact_name', 'r.check_in_date', 'r.check_out_date',
                'v.name as resort_name', 'v.address as resort_address', 'm.name as payment_method',
            ]);
        $review = DB::table('payment_reviews')->where('payment_id', $payment->id)
            ->where('decision', 'approved')->orderByDesc('id')->first();
        abort_unless($details && $review, 422, 'Payment approval details are incomplete.');

        $approvedAt = CarbonImmutable::parse($review->reviewed_at, 'Asia/Manila');
        $number = sprintf('CPR-%s-%06d', $approvedAt->format('Y'), $details->id);
        $currency = $details->currency === 'PHP' ? 'PHP' : $details->currency;
        $lines = [
            ['OFFICIAL PAYMENT RECEIPT', 18, true], [$details->resort_name, 14, true],
            [$details->resort_address, 9, false], ['', 10, false],
            ['Receipt No.: '.$number, 11, true],
            ['Approval date: '.$approvedAt->format('F j, Y g:i A').' (Asia/Manila)', 10, false],
            ['', 10, false], ['Received from: '.$details->contact_name, 11, false],
            ['Amount received: '.$currency.' '.number_format((float) $details->amount, 2), 14, true],
            ['Payment method: '.$details->payment_method, 10, false],
            ['Transaction reference: '.$details->reference_number, 10, false],
            ['Payment date: '.($details->payment_date ?: 'Not provided'), 10, false],
            ['', 10, false], ['Reservation reference: '.$details->booking_reference, 10, false],
            ['Stay dates: '.$details->check_in_date.' to '.$details->check_out_date, 10, false],
            ['', 10, false], ['Payment status: APPROVED', 11, true],
            ['This server-generated document confirms that the payment above was verified and recorded.', 9, false],
            ['It is distinct from the payment proof uploaded by the guest.', 9, false],
        ];
        $pdf = $this->pdf($lines, $number);

        return response($pdf, 200, [
            'Content-Type' => 'application/pdf',
            'Content-Disposition' => 'attachment; filename="official-receipt-'.$number.'.pdf"',
            'Content-Length' => (string) strlen($pdf),
            'X-Content-Type-Options' => 'nosniff', 'Cache-Control' => 'no-store, private',
        ]);
    }

    private function pdf(array $lines, string $number): string
    {
        $stream = "0.16 0.11 0.07 rg\n54 722 504 1 re f\n";
        $y = 755;
        foreach ($lines as [$text, $size, $bold]) {
            if ($text === '') {
                $y -= 12;

                continue;
            }
            foreach ($this->wrap($text, $size) as $part) {
                $font = $bold ? 'F2' : 'F1';
                $stream .= 'BT /'.$font.' '.$size.' Tf 54 '.$y.' Td ('.$this->escape($part).") Tj ET\n";
                $y -= $size + 7;
            }
        }
        $stream .= 'BT /F1 8 Tf 54 45 Td (Generated by Carlos Paradise reservation system - '.$this->escape($number).") Tj ET\n";
        $objects = [
            '<< /Type /Catalog /Pages 2 0 R >>',
            '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
            '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> /Contents 4 0 R >>',
            '<< /Length '.strlen($stream)." >>\nstream\n".$stream.'endstream',
            '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
            '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>',
        ];
        $pdf = "%PDF-1.4\n";
        $offsets = [0];
        foreach ($objects as $index => $object) {
            $offsets[] = strlen($pdf);
            $pdf .= ($index + 1)." 0 obj\n".$object."\nendobj\n";
        }
        $xref = strlen($pdf);
        $pdf .= "xref\n0 ".(count($objects) + 1)."\n0000000000 65535 f \n";
        for ($i = 1; $i <= count($objects); $i++) {
            $pdf .= str_pad((string) $offsets[$i], 10, '0', STR_PAD_LEFT)." 00000 n \n";
        }

        return $pdf."trailer\n<< /Size ".(count($objects) + 1)." /Root 1 0 R >>\nstartxref\n".$xref."\n%%EOF\n";
    }

    private function wrap(string $text, int $size): array
    {
        $converted = iconv('UTF-8', 'ASCII//TRANSLIT//IGNORE', $text);
        $ascii = $converted === false ? preg_replace('/[^\x20-\x7E]/', '?', $text) : $converted;

        return explode("\n", wordwrap($ascii, max(45, (int) floor(880 / $size)), "\n", true));
    }

    private function escape(string $text): string
    {
        return str_replace(['\\', '(', ')'], ['\\\\', '\\(', '\\)'], $text);
    }
}
